def score(pseudonymize, sets: list[tuple[str, tuple[str, ...]]]) -> tuple[int, int]:  # noqa: ANN001
    """Считает (скрыто слов, всего слов) по набору; pseudonymize(text) -> текст."""
    hit = total = 0
    for text, words in sets:
        out = pseudonymize(text)
        for word in words:
            total += 1
            hit += word not in out
    return hit, total


