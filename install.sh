#!/usr/bin/env bash
set -euo pipefail

# ─────────────────────────────────────────────────────────────────────────────
# labops-ai-assistant — единый установщик монорепо.
#
# ОДНА команда ставит ОБА компонента, которые входят в этот репозиторий:
#   1) agent-architecture — рантайм/жизненный цикл: зависимости, Claude Code,
#      автостарт и первый агент (Developer) со скиллом create-agent.
#   2) tg-plugin          — Telegram-канал. Берётся ЛОКАЛЬНО из этого дерева
#      (./tg-plugin), НЕ клонируется, и ставится автоматически в этом же прогоне.
#
# labops-second-brain (общая память) — внешняя зависимость, НЕ входит в монорепо;
# архитектурный установщик клонирует её рядом (в ~/labops-second-brain), если не
# задан SKIP_SECOND_BRAIN=1. Её собственная установка выполняется отдельно
# (sudo bash ~/labops-second-brain/scripts/install.sh) — см. README.
#
# Использование:
#   bash install.sh              # полный деплой (обе части)
#   bash install.sh --no-agent   # подготовить окружение, без создания агента
#   bash install.sh --test-only  # только self-test архитектуры
#   SKIP_SECOND_BRAIN=1 bash install.sh   # не клонировать общий мозг
#   SKIP_SELFTEST=1 bash install.sh       # не останавливать установку на self-test
#
# Все прочие флаги/переменные окружения пробрасываются в
# agent-architecture/install.sh без изменений.
# ─────────────────────────────────────────────────────────────────────────────

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ARCH="$ROOT/agent-architecture"
TG="$ROOT/tg-plugin"

[ -x "$ARCH/install.sh" ] || { echo "✗ не найден $ARCH/install.sh — репозиторий неполный" >&2; exit 1; }

# Монорепо-режим для архитектурного установщика:
#   • взять tg-plugin из локального дерева (не клонировать),
#   • поставить его автоматически (в контексте агентского пользователя).
export TG_PLUGIN_DIR="$TG"
export INSTALL_TG_LOCAL=1

# Единая точка входа: вся установка «зашита» здесь и делегируется архитектурному
# установщику (он владеет созданием non-root пользователя, Claude Code и агентом,
# а хвостом ставит локальный tg-plugin). exec — чтобы sudo -E внутри корректно
# пробросил окружение при ре-запуске от агентского пользователя.
exec bash "$ARCH/install.sh" "$@"
