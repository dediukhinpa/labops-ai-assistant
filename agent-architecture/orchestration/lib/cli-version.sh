#!/usr/bin/env bash
# cli-version.sh — замечает, что живая сессия исполняет устаревший Claude Code.
#
# ЗАЧЕМ. Нативный установщик обновляет CLI сам: качает новую версию в
# ~/.local/share/claude/versions/<версия> и перекидывает на неё симлинк
# ~/.local/bin/claude. Но уже запущенный процесс продолжает исполнять СТАРЫЙ
# файл — ядро держит открытым тот inode, с которого процесс стартовал. Сессия
# агента живёт неделями и пересоздаётся только при поломке, поэтому обновление
# до неё не доезжает никогда, а снаружи это не видно ничем: агент отвечает,
# watchdog доволен, версия в логах нигде не мелькает.
#
# Замерено на живом хосте 08.09.2026: на диске лежала 2.1.263 от 6 сентября, обе
# сессии от 3 сентября исполняли 2.1.259 — пять дней и две версии позади.
#
# Отставание бьёт не только по исправлениям. Алиасы моделей (`opus`, `sonnet`,
# `fable`) резолвит сам CLI при старте сессии, так что на старом бинаре агент
# уезжает на предыдущее поколение модели, а про новый алиас просто не знает.
#
# Библиотека только ОТВЕЧАЕТ на вопрос «дрейф есть?». Решение о перезапуске и
# выбор безопасного момента — за watchdog.sh.
#
# Тестовые точки подмены (см. cli-version.test.sh):
#   CLI_VERSION_PANE_PID_CMD  — команда, печатающая pid процесса сессии
#   CLI_VERSION_CLAUDE_BIN    — путь к эталонному бинарю вместо `command -v claude`
#   CLI_VERSION_CONFIG_JSON   — путь к ~/.claude.json вместо домашнего

# Свой каталог: рядом лежит скрипт правки конфига. Не трогаем SCRIPT_DIR — его
# при сорсинге перезаписывает lib/pane-recover.sh, и watchdog собирает по нему
# пути (та же грабля описана в lib/agent-env.sh).
_CLI_VERSION_LIB_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Печатает pid процесса, занимающего панель сессии. Пусто, если не определить.
# start-agent.sh запускает claude прямо командой панели, поэтому pane_pid — это
# и есть процесс claude, без спуска по дереву детей (проверено на живых сессиях).
_cli_version_pane_pid() {   # <session>
  local session="$1"
  if [ -n "${CLI_VERSION_PANE_PID_CMD:-}" ]; then
    "$CLI_VERSION_PANE_PID_CMD" "$session" 2>/dev/null || true
    return 0
  fi
  # display по одной панели, а не `list-panes | head -1`: list-panes отдаёт все
  # панели окна, и по «=имя:» — окна ТЕКУЩЕГО. Открой оператор в сессии второе
  # окно, сюда пришёл бы pid его bash, дрейф «нашёлся» бы на любом простое, и
  # агент ушёл бы в рестарт. Цель — первое окно, его верхняя левая панель.
  tmux display -p -t "=$session:^.{top-left}" '#{pane_pid}' 2>/dev/null || true
}

# Печатает путь бинаря, который РЕАЛЬНО исполняет процесс. Пусто, если /proc
# недоступен (процесс умер между проверками) или бинарь удалён — readlink в этом
# случае даёт суффикс " (deleted)", такой путь для сравнения бесполезен.
cli_version_running_exe() {   # <session>
  local pid exe
  pid="$(_cli_version_pane_pid "$1")"
  case "${pid:-}" in ''|*[!0-9]*) return 0;; esac
  exe="$(readlink -f "/proc/$pid/exe" 2>/dev/null || true)"
  case "$exe" in *' (deleted)'|'') return 0;; esac
  printf '%s\n' "$exe"
}

# Печатает путь бинаря, который получит СЛЕДУЮЩИЙ старт. Пусто, если claude не
# найден: в этом случае судить о дрейфе не по чему.
cli_version_installed_exe() {
  local bin
  bin="${CLI_VERSION_CLAUDE_BIN:-$(command -v claude 2>/dev/null || true)}"
  # -e обязателен: `readlink -f` канонизирует и НЕСУЩЕСТВУЮЩИЙ путь, если
  # существуют его родительские каталоги. Без этой проверки пропавший бинарь
  # давал непустой ответ, не равный запущенному, и читался как дрейф.
  [ -n "$bin" ] && [ -e "$bin" ] || return 0
  readlink -f "$bin" 2>/dev/null || true
}

# Короткая метка версии для лога. Нативный установщик кладёт КАЖДУЮ версию
# отдельным исполняемым файлом с именем версии (~/.local/share/claude/versions/
# 2.1.263 — это сам бинарь, а не каталог с бинарём внутри, проверено на хосте
# 08.09.2026), поэтому имя файла и есть версия.
cli_version_label() {   # <путь к бинарю>
  local p="${1:-}"
  [ -n "$p" ] || { printf '%s\n' 'неизвестна'; return 0; }
  basename "$p"
}

# Возвращает 0, если сессия исполняет не тот бинарь, что лежит на диске.
#
# FAIL-OPEN НАМЕРЕННО: любая неопределённость (нет сессии, /proc не читается,
# claude не найден) — это «дрейфа нет», то есть перезапуска не будет. Ошибочный
# перезапуск стоит агенту потерянной работы, а лишний цикл на старой версии не
# стоит ничего: следующий проход watchdog повторит проверку через полминуты.
cli_version_drifted() {   # <session>
  local running installed
  running="$(cli_version_running_exe "$1")"
  [ -n "$running" ] || return 1
  installed="$(cli_version_installed_exe)"
  [ -n "$installed" ] || return 1
  [ "$running" != "$installed" ]
}

# ── Мастер первого запуска ───────────────────────────────────────────────────
# Claude Code держит в ~/.claude.json метку пройденного онбординга вместе с
# версией, на которой его проходили. Нативный установщик обновляет CLI сам, а
# watchdog на это обновление ЕЩЁ И перезапускает сессию (см. cli_version_drifted)
# — и свежий процесс, увидев расхождение метки с установленной версией,
# показывает мастер первого запуска: выбор темы, следом способ входа.
#
# Для агента это тупик. Пока мастер на экране, сессия не доходит до промпта,
# MCP-серверы не стартуют, канал не поднимает свой порт — агент нем, хотя
# процесс жив и панель отрисована. Замер на живом хосте 09.09.2026: обе сессии
# простояли на выборе темы двое суток, :6000 и :6001 не слушал никто.
#
# Ответы мастера оператор дал ещё при установке роя, поэтому метку проставляем
# сами перед каждым стартом. Каждый раз, а не однажды: ~/.claude.json общий на
# все сессии хоста, и каждая переписывает его целиком своей копией из памяти —
# однократный засев чужой сброс пережил бы не обязательно.
#
# Точка подмены для теста: CLI_VERSION_CONFIG_JSON — путь к файлу конфига.
cli_version_mark_onboarding_done() {
  local cfg version
  cfg="${CLI_VERSION_CONFIG_JSON:-$HOME/.claude.json}"
  version="$(cli_version_label "$(cli_version_installed_exe)")"
  # «неизвестна» — ответ cli_version_label на отсутствующий бинарь. Записать её
  # в метку значит соврать CLI про версию: пусть лучше выйдет мастер, чем агент
  # поедет с меткой, которой не соответствует ничто.
  [ -n "$version" ] && [ "$version" != "неизвестна" ] || return 0
  [ -f "$cfg" ] || printf '{}' > "$cfg"
  CFG="$cfg" VERSION="$version" python3 "$_CLI_VERSION_LIB_DIR/cli-onboarding-mark.py" || true
}
