#!/usr/bin/env bash
# preflight.sh — проверка доступности внешних хостов ДО начала установки.
#
# ЗАЧЕМ. Установка тянет из сети бинарь Claude Code и клонирует соседние
# репозитории. Если хост режется с этой машины, раньше это всплывало глубоко
# внутри установки и без объяснения: `curl -fsSL … | bash` под `set -e` +
# `pipefail` роняет весь скрипт кодом 22, и сообщение об ошибке, написанное
# НИЖЕ по тексту, уже не выполняется. Оператор видел обрыв на середине и одну
# строку `curl: (22)` (случай 08.09.2026, Ubuntu 22.04 в Амстердаме).
#
# Проверить связь до того, как что-либо установлено и создан пользователь,
# стоит одну секунду и экономит разбор на полпути.
#
# ПОЧЕМУ 403 ОТДЕЛЬНО ОТ «НЕТ СВЯЗИ». Так отвечает Cloudflare перед claude.ai,
# когда адрес закрыт: либо неподдерживаемый регион, либо репутация адреса
# датацентра. Это не сетевой сбой — повторять, менять DNS и ждать бесполезно,
# лечится только другим хостом или маршрутом. Сваливать это в общее «сеть
# недоступна» значит послать оператора чинить не то.

PREFLIGHT_CONNECT_TIMEOUT="${PREFLIGHT_CONNECT_TIMEOUT:-7}"
PREFLIGHT_MAX_TIME="${PREFLIGHT_MAX_TIME:-20}"

# http_status <url> — код HTTP-ответа, либо 000, если соединения нет вовсе.
#
# HEAD, а не GET: проба не должна тянуть тело (github.com — сотни килобайт).
# Метод роли не играет — нам важен сам факт ответа, и 405 «метод не разрешён»
# от api.anthropic.com такой же годный признак живого хоста, как и 200.
http_status() {   # <url>
  local code
  code="$(curl -sSI -o /dev/null -w '%{http_code}' \
          --connect-timeout "$PREFLIGHT_CONNECT_TIMEOUT" \
          --max-time "$PREFLIGHT_MAX_TIME" "$1" 2>/dev/null)" || true
  printf '%s' "${code:-000}"
}

# preflight_host <url> — 0 доступен, 1 нет связи, 2 режется (403).
#
# Доступным считаем ЛЮБОЙ HTTP-ответ кроме 403: 302 у claude.ai, 405 у
# api.anthropic.com, 404 у несуществующего пути — всё это значит, что хост нас
# слышит, а установщику ровно это и нужно знать.
preflight_host() {   # <url>
  local code
  code="$(http_status "$1")"
  case "$code" in
    000) return 1 ;;
    403) return 2 ;;
    *)   return 0 ;;
  esac
}
